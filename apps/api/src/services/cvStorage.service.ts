import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { ReadStream } from 'node:fs';
import { fileExtension } from '@onsys/shared';
import { env } from '../lib/env';
import { logger } from '../lib/logger';

/**
 * Where candidate CVs live.
 *
 * On disk, under CV_STORAGE_DIR, which is a volume in production. Three
 * alternatives were considered and rejected:
 *
 *   - In the database as bytes. Backs itself up, but puts 10 MB blobs through
 *     every pg_dump and every query plan that touches the table.
 *   - Azure Blob with SAS download links, which is what the standalone
 *     cv-post-app does. It works, but a SAS URL is a bearer token in a query
 *     string: once minted it is valid for anyone who has it, including after
 *     it has been pasted into a chat or a ticket. Adding a storage account and
 *     its keys for that is a poor trade when the api already has a volume.
 *   - A public directory served by nginx. A CV is personal information; there
 *     must be no URL that returns one without a session behind it.
 *
 * So: written here, read back only by the admin download handler, which checks
 * the session first and streams the bytes through the api. The only way to a
 * CV is an authenticated request, and that request is logged.
 *
 * The module is deliberately free of Prisma and Express. It knows about bytes
 * and paths; the route knows about people.
 */

/** Resolved once. Relative in dev, an absolute mount path in production. */
const ROOT = path.resolve(env.CV_STORAGE_DIR);

/**
 * Build the storage key for a new upload.
 *
 * The candidate's filename is never part of the path. It arrives from a
 * browser, so it can contain "../", a null byte, a Windows device name, 400
 * characters of Unicode, or the name of a file we already have — all of which
 * are somebody else's bug report. The key is a UUID plus the extension we
 * validated, under a month-stamped folder so a directory listing stays
 * navigable and a retention sweep can work a month at a time.
 */
export function buildCvKey(originalName: string, now: Date = new Date()): string {
  const ext = fileExtension(originalName);
  const month = `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, '0')}`;
  return `${month}/${randomUUID()}${ext}`;
}

/**
 * Resolve a stored key to an absolute path, refusing anything that escapes.
 *
 * Keys are generated by buildCvKey, so in normal operation this can never
 * fail. It is here because the key reaches this function from a database row,
 * and "the database is trusted" is the assumption every path-traversal
 * write-up opens with. One cheap check keeps a corrupted or hand-edited row
 * from reading /etc/shadow.
 */
function resolveWithinRoot(key: string): string {
  const full = path.resolve(ROOT, key);
  const prefix = ROOT.endsWith(path.sep) ? ROOT : ROOT + path.sep;
  if (full !== ROOT && !full.startsWith(prefix)) {
    throw new Error(`CV storage key escapes the storage root: ${key}`);
  }
  return full;
}

export interface StoredCv {
  key: string;
  bytes: number;
  /** SHA-256 of the file, logged so a duplicate submission is recognisable. */
  sha256: string;
}

/** Write an uploaded CV and return what the database needs to find it again. */
export async function storeCv(originalName: string, data: Buffer): Promise<StoredCv> {
  const key = buildCvKey(originalName);
  const full = resolveWithinRoot(key);

  await mkdir(path.dirname(full), { recursive: true });
  // wx: never overwrite. A UUID collision is not a real risk, but silently
  // replacing one candidate's CV with another's is bad enough to be worth a
  // flag that makes it impossible rather than unlikely.
  await writeFile(full, data, { flag: 'wx' });

  return {
    key,
    bytes: data.byteLength,
    sha256: createHash('sha256').update(data).digest('hex'),
  };
}

/** Open a stored CV for streaming to an authenticated admin. */
export async function openCv(key: string): Promise<{ stream: ReadStream; bytes: number }> {
  const full = resolveWithinRoot(key);
  const info = await stat(full);
  return { stream: createReadStream(full), bytes: info.size };
}

/**
 * Delete a stored CV.
 *
 * Never throws for a file that is already gone. Deleting an application must
 * succeed even when its file was lost to a restore or removed by hand, or the
 * row becomes undeletable and we are left holding personal information we were
 * asked to erase.
 */
export async function deleteCv(key: string): Promise<void> {
  try {
    await rm(resolveWithinRoot(key), { force: true });
  } catch (err) {
    logger.error({ err, key }, 'Failed to delete a stored CV');
  }
}

/**
 * Create the storage directory at boot.
 *
 * Called from server startup so a misconfigured volume is a loud error on
 * deploy rather than a 500 for the first candidate who tries to apply. A
 * failure here is logged, not thrown: the rest of the site should stay up.
 */
export async function ensureCvStorage(): Promise<boolean> {
  try {
    await mkdir(ROOT, { recursive: true });
    logger.info({ dir: ROOT }, 'CV storage ready');
    return true;
  } catch (err) {
    logger.error(
      { err, dir: ROOT },
      'CV storage directory is not writable — job applications will fail until this is fixed',
    );
    return false;
  }
}

/** Exposed for the health endpoint and for tests. */
export const cvStorageRoot = ROOT;
